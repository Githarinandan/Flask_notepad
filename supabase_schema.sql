-- Run this once in Supabase Dashboard > SQL Editor.

create table if not exists public.notes (
    id bigint generated by default as identity primary key,
    title text not null,
    content text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- The Flask backend uses a Supabase secret key. Keep that key on the server.
-- RLS remains enabled; the secret key uses the service_role and bypasses RLS.
alter table public.notes enable row level security;

grant all on table public.notes to service_role;
grant usage, select on sequence public.notes_id_seq to service_role;

-- Automatically refresh updated_at whenever a note is edited.
create or replace function public.set_notes_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists notes_set_updated_at on public.notes;
create trigger notes_set_updated_at
before update on public.notes
for each row
execute function public.set_notes_updated_at();
